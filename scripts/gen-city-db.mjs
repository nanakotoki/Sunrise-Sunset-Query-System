function parse(block) {
  return block
    .split('\n')
    .filter((l) => l.trim())
    .map((line) => {
      const [zh, aliases, lat, lng] = line.split('|');
      const aliasList = aliases
        .split(',')
        .map((a) => a.trim())
        .filter(Boolean)
        .map((a) => `'${a.replace(/'/g, "\\'")}'`)
        .join(', ');
      return `  { zh: '${zh}', aliases: [${aliasList}], lat: ${lat}, lng: ${lng} },`;
    })
    .join('\n');
}

